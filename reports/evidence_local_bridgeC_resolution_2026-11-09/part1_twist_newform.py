# Local-derived. PARI (cypari2) exact checks: Task 1 (twist/isogeny/symbols), Task 2 (newform vs carrier).
import cypari2; pari=cypari2.Pari(); pari.allocatemem(4*10**9); pari.set_real_precision(38)
P=lambda s: pari(s)
print("PARI", P("version()"))
P("E=ellinit([1,-1,0,-2,-1]); Ep=ellinit(elltwist(E,140)); Em=ellinit(elltwist(E,-20)); E7=ellinit(elltwist(E,-7))")
for nm in ["E","Ep","Em","E7"]:
    print(nm, "a-inv", P(f"{nm}[1..5]"), "cond", P(f"ellglobalred({nm})[1]"), "rootno", P(f"ellrootno({nm})"), "j", P(f"{nm}.j"))
print("ellidentify E:", P("iferr(ellidentify(E)[1][1],e,\"no-db\")"))
print("ellidentify Ep:", P("iferr(ellidentify(Ep)[1][1],e,\"no-db\")"), " Em:", P("iferr(ellidentify(Em)[1][1],e,\"no-db\")"))
print("ellisisom(Ep,Em) =", P("ellisisom(Ep,Em)"))
print("isogeny class of Ep (size, matrix):", P("my(c=ellisomat(Ep)); [#c[1], c[2]]"))
print("isogeny class curves of Ep (short W):", P("ellisomat(Ep,,1)[1]"))
print("ellisisom(Em, class curve i), i=1..4:", P("my(c=ellisomat(Ep,,1)); vector(#c[1],i,ellisisom(Em,ellinit(c[1][i])))"))
print("ellisisom(Ep, class curve i), i=1..4:", P("my(c=ellisomat(Ep,,1)); vector(#c[1],i,ellisisom(Ep,ellinit(c[1][i])))"))
# Sturm bound for weight 2 on Gamma0(19600): (k/12)*index
print("index Gamma0(19600) =", P("19600*prod(i=1,#factor(19600)[,1],1+1/factor(19600)[i,1])"), " Sturm=", P("floor(2/12*19600*prod(i=1,#factor(19600)[,1],1+1/factor(19600)[i,1]))+1"))
print("all a_n equal (Ep vs Em), n<=7000:", P("ellan(Ep,7000)==ellan(Em,7000)"))
print("a_n(Xi) == chi140(n) a_n(49a1), all n<=7000:", P("my(a=ellan(E,7000),b=ellan(Ep,7000)); b==vector(7000,n,kronecker(140,n)*a[n])"))
print("a_n(Xi) == chi_-20(n) a_n(49a1), all n<=7000:", P("my(a=ellan(E,7000),b=ellan(Ep,7000)); b==vector(7000,n,kronecker(-20,n)*a[n])"))
print("CM: a_n(49a1)==chi_-7(n)a_n(49a1) n<=7000:", P("my(a=ellan(E,7000)); a==vector(7000,n,kronecker(-7,n)*a[n])"))
print("CM for Xi: a_n(Xi)==chi_-7(n)a_n(Xi):", P("my(a=ellan(Ep,7000)); a==vector(7000,n,kronecker(-7,n)*a[n])"))
print("chi140 == chi_-20*chi_-7 on n<=1000:", P("vector(1000,n,kronecker(140,n))==vector(1000,n,kronecker(-20,n)*kronecker(-7,n))"))
print("chi140(-1),chi_-20(-1),chi_-20(-49):", P("[kronecker(140,-1),kronecker(-20,-1),kronecker(-20,-49)]"))
# functional-equation check of Xi's L-function and root number
print("lfuncheckfeq(Xi) (bits, <= -100 means OK):", P("lfuncheckfeq(lfuncreate(Ep))"))
print("lfunrootres(Xi) root number:", P("lfunrootres(lfuncreate(Ep))[3]"))
print("analytic rank Xi:", P("ellanalyticrank(Ep)[1]"), " L'(Xi,1)=", P("ellanalyticrank(Ep)[2]"))
print("analytic rank 49a1:", P("ellanalyticrank(E)[1]"), " L(49a1,1)=", P("ellanalyticrank(E)[2]"))
# control element STS^-1 vs S^-1T^-1S
P("S=[0,-1;1,0]; T=[1,1;0,1]")
print("S*T*S^-1 =", P("S*T*S^-1"), " S^-1*T^-1*S =", P("S^-1*T^-1*S"))
# ---- Task 2: newform f of 49a1 as CM theta series on L1 = O_{Q(sqrt-7)} ----
# alpha = x + y*w, w=(1+sqrt-7)/2; N(alpha)=x^2+xy+2y^2; alpha mod sqrt-7 == x+4y mod 7; Re(alpha)=x+y/2
B=600
P(f"B={B}")
P("th=vector(B,n,0); R=ceil(sqrt(4*B)); for(x=-R,R,for(y=-R,R,my(n=x^2+x*y+2*y^2); if(n>=1&&n<=B, th[n]+=kronecker(x+4*y,7)*(x+y/2)))); th=th/2")
print("f_49a1 == (1/2) sum_{alpha in O} (alpha|sqrt-7) alpha q^N(alpha), n<=B:", P("th==ellan(E,B)"))
# mf side: level-49 weight-2 decomposition of theta_{L49} = theta1(tau)*theta1(7tau)
P("Q1=[2,1;1,4];")
P("mf2=mfinit([49,2],1); mfe=mfinit([49,2],3); mfall=mfinit([49,2]);")
print("dim S2(49), E2(49), M2(49):", P("[mfdim(mf2),mfdim(mfe),mfdim(mfall)]"))
P("thL1=mffromqf(Q1)[2]; thL1_7=mfbd(thL1,7); thL49=mfmul(thL1,thL1_7);")
P("v=mftobasis(mfall,thL49); bas=mfbasis(mfall); fnew=mfeigenbasis(mf2)[1]; ")
print("theta_L49 in M2(Gamma0(49)) coords:", P("v~"))
P("Cs=mftobasis(mfall,fnew); Ecoords=[mftobasis(mfall,g)|g<-mfbasis(mfe)]; Mt=matconcat(concat(Ecoords,[Cs])); c=matsolve(Mt,v);")
print("theta_L49 = Eis + c*f, c =", P("c[#c]"))
print("check coeffs: theta_L49 - c*f in Eisenstein space -> residual", P("mfcoefs(mflinear([thL49,fnew],[1,-c[#c]]),200)==mfcoefs(mflinear(mfbasis(mfe),vector(#Ecoords,i,c[i])),200)"))
print("Fricke on cusp part: mfatkin of f at Q=49 eigen:", P("mfatkininit(mf2,49)[2]"))
# twist of the weight-2 carrier F2=(theta1^2, 7theta1(7.)^2) by chi140
P("g1=mfmul(thL1,thL1); g2=mfbd(g1,7); co1=mfcoefs(g1,300); co2=mfcoefs(g2,300); fx=concat(0,ellan(Ep,300));")
P("tw(co)=vector(#co,i,kronecker(140,i-1)*co[i])")
print("R_chi140(theta1(7.)^2) == 0 (n<=300):", P("tw(co2)==vector(301,i,0)"))
print("R_chi140(theta1^2) first coeffs:", P("tw(co1)[1..20]"))
print("f_Xi first coeffs:", P("fx[1..20]"))
print("f_Xi in span R_chi(F2)? solve c*tw(co1)=fx :", P("my(t=tw(co1),k=0); for(i=2,#t,if(t[i],k=i;break)); my(cc=fx[k]/t[k]); [cc, cc*t==fx]"))
# weight-4: theta_L49^2 cusp part vs f^2
P("mf4=mfinit([49,4],1); mf4all=mfinit([49,4]); mfe4=mfinit([49,4],3); T2=mfmul(thL49,thL49); fsq=mfmul(fnew,fnew);")
print("dim S4(49):", P("mfdim(mf4)"))
P("ws=mftobasis(mfall=mf4all,T2); Ec4=[mftobasis(mf4all,g)|g<-mfbasis(mfe4)]; Cb4=[mftobasis(mf4all,g)|g<-mfbasis(mf4)]; M4=matconcat(concat(Ec4,Cb4)); sol=matsolve(M4,ws); cusp=mflinear(mfbasis(mf4),vector(#Cb4,i,sol[#Ec4+i]));")
print("cusp part of theta_L49^2 coeffs:", P("mfcoefs(cusp,8)"))
P("fs=mftobasis(mf4,fsq); cp=mftobasis(mf4,cusp);")
print("f^2 in S4(49)?", P("#fs>0"), " cusp(theta_L49^2) proportional to f^2?", P("matrank(matconcat([fs,cp]))==1"))
print("Fricke eigen of f^2 (mfatkin Q=49): f^2|W == f^2 ?", P("my(A=mfatkininit(mf4,49)[2]); A*fs==fs"))
print("rank [f^2, cusp(theta^2)] :", P("matrank(matconcat([fs,cp]))"))
