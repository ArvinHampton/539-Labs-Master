# Transparent Eisenstein test for the positive part of u_L at the minimal modulus: is the sigma-symmetrised indicator of
# S+ u S- (classes C, C+d, sigma C, sigma C+d) a union of cosets of H = common kernel of the sigma-invariant characters?
import cypari2, itertools, numpy as np, math
from fractions import Fraction as Fr
pari=cypari2.Pari(); pari.allocatemem(10**9)
CFG={7:(35,1,[(2,1),(5,1)]),8:(3,4,[(2,2),(3,1)]),11:(11,3,[(2,1),(3,2)])}
for s,(D0,c,pe) in CFG.items():
    d=2*(s-2); K=pari(f'bnfinit(x^2-{D0},1)'); w=pari('Mod(x,x^2-%d)'%D0)
    sig=[g for g in pari.nfgaloisconj(K) if str(g)!='x'][0]
    mod=pari.idealhnf(K,1); Ps=[]
    for p,e in pe:
        for P in pari.idealprimedec(K,p): Ps.append(P); mod=pari.idealmul(K,mod,pari.idealpow(K,P,e))
    bnr=pari.bnrinit(K,[mod,[1,1]],1); cyc=[int(z) for z in pari('(b)->b.cyc')(bnr)]
    cl=lambda J: tuple(int(z) for z in pari.bnrisprincipal(bnr,J,0))
    Nm=int(pari.idealnorm(K,mod))
    dd=cl(pari.idealhnf(K,1-1000*Nm))
    a=(Fr(s,2*(s-2)),Fr(-1,s-2)); X0=(int(d*a[0]),int(d*a[1])); beta=lambda X1,X2:(2*X1+s*X2)+c*X2*w
    Dp=pari.idealhnf(K,beta(*X0))
    for gg in (beta(d,0),beta(0,d)): Dp=pari.idealadd(K,Dp,gg)
    # S+ classes (coprime part) for a few cone points
    Sp=set()
    for n in range(-30,31):
        for k in range(0,31):
            X1=d*n+X0[0]; X2=d*k+X0[1]
            if not (X2>=0 and (X1*2-X2*(-1))>0): continue   # cone [e1, gamma e1), gamma e1=(-1,2)
            J=pari.idealdiv(K,beta(X1,X2),Dp); cp=0; Jp=J
            for P in Ps:
                v=int(pari.idealval(K,J,P))
                if v: cp+=v; Jp=pari.idealdiv(K,Jp,pari.idealpow(K,P,v))
            Sp.add((cp,cl(Jp)))
    allc=list(itertools.product(*[range(m) for m in cyc]))
    sigc={x:cl(pari.nfgaloisapply(K,sig,pari.idealhnf(K,1))) for x in []}
    gens=pari('(b)->b.gen')(bnr)
    Sg=np.array([[int(z) for z in cl(pari.nfgaloisapply(K,sig,g))] for g in gens]).T
    sg=lambda x: tuple(int(v)%m for v,m in zip(Sg@np.array(x),cyc))
    add=lambda x,y: tuple((u+v)%m for u,v,m in zip(x,y,cyc))
    neg=lambda x: tuple((-u)%m for u,m in zip(x,cyc))
    # H = subgroup generated by (sigma-1)G  (common kernel of sigma-invariant chars is exactly image of (1-sigma)... check by counting)
    img={add(sg(x),neg(x)) for x in allc}
    H={(0,)*len(cyc)}
    while True:
        new={add(u,v) for u in H for v in img}|H
        if new==H: break
        H=new
    ninv=sum(1 for ch in allc if all(abs(sum(cc*(vv)/m for cc,vv,m in zip(ch,sg(x),cyc))-sum(cc*vv/m for cc,vv,m in zip(ch,x,cyc)))%1<1e-12 for x in [tuple(int(i==j) for i in range(len(cyc))) for j in range(len(cyc))]))
    print(f"s={s}: Cl_m^+ = {cyc}, |G|={math.prod(cyc)}, #sigma-inv chars={ninv}, |(1-sigma)G| = {len(H)} (should be |G|/#inv = {math.prod(cyc)//ninv}); d = {dd}")
    for cp in sorted({c0 for c0,_ in Sp}):
        C=[x for c0,x in Sp if c0==cp]
        Fset={}
        for x in C:
            for y in (x,add(x,dd),sg(x),add(sg(x),dd)): Fset[y]=Fset.get(y,0)+1
        # is the support a union of H-cosets with constant multiplicity?
        ok=all(Fset.get(add(y,h),0)==m for y,m in Fset.items() for h in H)
        print(f"   C-part valuation sum {cp}: S+ classes {sorted(C)}; sym-support size {len(Fset)}, multiplicities {sorted(set(Fset.values()))}; H-coset union (=> Eisenstein): {ok}")
