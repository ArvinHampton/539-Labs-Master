def kappa_with(Lvals,i,h):
    Fh={tuple(e['chi']):float(fr(e['abs']))*cmath.exp(2j*math.pi*float(fr(e['phase_turns']))) for e in CS[str(i)]['data']['1']['cusp_coeffs']}
    z0={c:sum(ev(chi,c).conjugate()*Lvals.get(chi,0) for chi in chars)/96 for c in chars}
    return sum(sum(Fh[chi]*ev(chi,c) for chi in Fh)*cmath.exp(2j*math.pi*normcls[c]*h/140)*z0[c] for c in chars)
contrib=set()
for i in C:
    Fh={tuple(e['chi']) for e in CS[str(i)]['data']['1']['cusp_coeffs']}
# which characters actually carry weight: compute Ghat over all chars for row 73, h=1
i=73
Fh={tuple(e['chi']):float(fr(e['abs']))*cmath.exp(2j*math.pi*float(fr(e['phase_turns']))) for e in CS[str(i)]['data']['1']['cusp_coeffs']}
Gc={c:sum(Fh[chi]*ev(chi,c) for chi in Fh)*cmath.exp(2j*math.pi*normcls[c]/140) for c in chars}
Gh={chi:sum(Gc[c]*ev(chi,c).conjugate() for c in chars)/96 for chi in chars}
nzc=[chi for chi in chars if abs(Gh[chi])>1e-12]
odd=[chi for chi in nzc if LV[chi]['cond_inf']==[1,1]]
L0d={chi:LV[chi]['L0'] for chi in chars}
Lhd={chi:LV[chi]['Lhalf_prim'] for chi in chars if 'Lhalf_prim' in LV[chi]}
out=[f"row 73, h=1: characters with nonzero weight: {len(nzc)} (all cusp characters: {all(chi in Lhd for chi in nzc)}); totally odd among them: {len(odd)}"]
