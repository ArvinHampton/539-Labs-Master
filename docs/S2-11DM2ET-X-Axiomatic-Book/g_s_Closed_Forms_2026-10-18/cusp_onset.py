# Step (5): narrow class number h+ (SL2(Z)-classes of primitive forms = cycles of reduced forms) vs number of genera (cosets of
# principal-form values in (Z/D)^x), for the discriminant D(s) of the primitive integral form attached to Q2 (D=4s(s-2) s odd, s(s-2) s even).
from math import gcd, isqrt
import json
def D_of(s): return 4*s*(s-2) if s % 2 else s*(s-2)
def reduced_forms(D):
    r = isqrt(D); L = []
    for b in range(1, r+1):
        if b > r or (D - b*b) % 4: continue
        if b*b >= D: continue
        ac = (b*b - D)//4
        for a in range(-2*r, 2*r+1):
            if a == 0 or ac % a: continue
            c = ac//a
            if gcd(gcd(abs(a), b), abs(c)) != 1: continue
            if r - b < 2*abs(a) <= r + b and (b*b < D) and not (2*abs(a) == r + b):  # integer version of sqrt(D)-b < 2|a| < sqrt(D)+b
                import math
                sd = math.sqrt(D)
                if sd - b < 2*abs(a) < sd + b: L.append((a, b, c))
    return sorted(set(L))
def rho(f, D):
    import math
    a, b, c = f; sd = math.sqrt(D); m = 2*abs(c)
    # b' = -b mod 2|c|, with sqrt(D)-2|c| < b' < sqrt(D)
    bp = (-b) % m
    while bp < sd - m: bp += m
    while bp > sd: bp -= m
    return (c, bp, (bp*bp - D)//(4*c))
def narrow_classes(D):
    R = reduced_forms(D); seen = set(); cycles = []
    for f in R:
        if f in seen: continue
        cyc = [f]; seen.add(f); g = rho(f, D)
        while g != f:
            assert g in R, (g, D); seen.add(g); cyc.append(g); g = rho(g, D)
        cycles.append(cyc)
    return cycles
def genera(D, reps, B=40):
    def vals(f):
        a, b, c = f; V = set()
        for x in range(-B, B+1):
            for y in range(-B, B+1):
                v = a*x*x + b*x*y + c*y*y
                if v and gcd(v, D) == 1: V.add(v % D)
        return V
    P = vals(reps[0]); H = {1}
    for p in P:  # closure: subgroup generated by principal values
        H = H | {(h*p) % D for h in H}
    changed = True
    while changed:
        new = {(h1*h2) % D for h1 in H for h2 in H} | H
        changed = len(new) > len(H); H = new
    keys = set()
    for f in reps:
        v = next(iter(vals(f))); keys.add(min((v*h) % D for h in H))
    return len(keys)
S = list(range(3, 21)) + [25, 30, 41]; rows = []
for s in S:
    D = D_of(s); cyc = narrow_classes(D); reps = [c[0] for c in cyc]
    # put principal form first
    prin = next(i for i, c in enumerate(cyc) if any(f[0] == 1 for f in c)); reps.insert(0, reps.pop(prin))
    hp = len(cyc); gn = genera(D, reps)
    rows.append(dict(s=s, D=D, hplus=hp, genera=gn, cusp_part=hp != gn))
    print(f"s={s:2d} D={D:5d} h+={hp:3d} genera={gn:3d}  Cl+/genus nontrivial (cusp part expected): {hp != gn}", flush=True)
json.dump(rows, open('cusp_onset.json', 'w'), indent=1)
